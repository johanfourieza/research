suppressPackageStartupMessages({library(tidyverse);library(here);library(digest)})
out<-here::here("replication","work","analysis","simulation","revised_primary1795_addon")
code<-list.files(here::here("replication","R"),pattern='^simulation_addon_.*[.]R$',full.names=TRUE)
walk(code,~invisible(parse(file=.x)))
snap<-file.path(out,'code_snapshot');dir.create(snap,showWarnings=FALSE)
manifest<-file.path(out,'frozen_addon_code_manifest.csv')
if(file.exists(manifest))stop('Add-on code is already frozen.')
walk(code,~file.copy(.x,file.path(snap,basename(.x)),overwrite=FALSE))
write_csv(tibble(file=basename(code),sha256=map_chr(code,~digest(file=.x,algo='sha256')),frozen_at=as.character(Sys.time())),manifest)
cat('All add-on scripts parse; snapshots and SHA256 manifest frozen.\n')
